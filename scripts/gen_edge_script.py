#!/usr/bin/env python3
"""Generate the Bunny Edge Script of legacy redirects (infra/edge/redirects.js).

    python3 -I scripts/gen_edge_script.py           # writes infra/edge/redirects.js
    python3 -I scripts/gen_edge_script.py --check   # fails if the versioned file is stale (CI)

Orange Juice v3 URLs are path-only (`/16139/nick.htm`), except the query strings that select
content (`/index.htm?idcat=3&OJ_NEWS_QRYpg=2`, `/nicklist.htm?idgroup=12`), the searches and
the click counters (`golink.htm?url=`). The archive keeps the paths (lower-cased: IIS was
case-insensitive, bunny.net is not) and folds the content parameters into the file name
(scripts/statify.py `static_name`). The edge script (a middleware of the pull zone, see
infra/main.tf) applies the same rules, so it needs no list of URLs:

  - `*.htm` path with upper-case letters -> 301 to the lower-case path
  - known content parameters -> 301 to the static name (`/index-cat3-p2.htm`); other
    parameters are dropped (`/nick.htm?x=1` -> `/nick.htm`)
  - searches (`?sn=`, `?snick=`...) -> 301 to `/oj-search.htm?t=<type>&q=<words>`
  - `golink.htm?url=<ojuice.net URL or path>` -> resolved like that URL; other targets -> 404
    (no open redirect on this domain)
  - write, login and admin pages -> 301 /archived.htm
  - everything else passes through untouched (fast path: no query string and no capital)

The rules come from scripts/statify.py (REMOVED, QUERY_KEYS, SEARCH_KEYS), so the script
cannot drift from the build. Standard library only. Test: node scripts/test_edge_script.mjs
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "infra" / "edge" / "redirects.js"
SDK = "https://esm.sh/@bunny.net/edgescript-sdk@0.13.0"


def statify():
    spec = importlib.util.spec_from_file_location("statify", REPO / "scripts" / "statify.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render() -> str:
    st = statify()
    data = {
        "removed": sorted(st.REMOVED),
        "queryKeys": [[k, v] for k, v in st.QUERY_KEYS.items()],
        "searchKeys": [[k, v] for k, v in st.SEARCH_KEYS.items()],
        "archived": st.ARCHIVED,
        "searchPage": st.SEARCH_PAGE,
        "skins": [s for s in st.SKINS if s != st.DEFAULT_SKIN],
        "hosts": list(st.OWN_HOSTS),
    }
    blob = json.dumps(data, indent=None, separators=(",", ":"), ensure_ascii=True)
    return f"""// GENERATED by scripts/gen_edge_script.py from the rules of scripts/statify.py:
// do not edit, regenerate.
//
// Bunny Edge Script (middleware of the pull zone, infra/main.tf): old URLs of www.ojuice.net
// (Orange Juice v3) -> 301 to their static page. Runs on origin requests only (cache misses;
// the pull zone caches per query string). See the docstring of gen_edge_script.py.
// Test: node scripts/test_edge_script.mjs

import * as BunnySDK from "{SDK}";

// BEGIN resolve (pure, tested by scripts/test_edge_script.mjs)
const DATA = {blob};
const REMOVED = new Set(DATA.removed);
const HOSTS = new Set(DATA.hosts);
const NOT_FOUND = {{ status: 404 }};
function foreign(pathname) {{
  let d;
  try {{ d = decodeURIComponent(pathname); }} catch (e) {{ d = pathname; }}
  return /^[\\/\\\\]{{2}}/.test(d);   // "//host" or "/\\host": a protocol-relative URL once in Location
}}
const moved = (location) => ({{ status: 301, location }});

// -> null (serve the request as is), {{status: 301, location}} or {{status: 404}}.
function resolve(pathname, search, depth = 0) {{
  let path;
  try {{ path = decodeURIComponent(pathname); }} catch (e) {{ path = pathname; }}
  let prefix = "";
  const sm = /^\\/skin\\/([^\\/]+)(\\/.*)$/.exec(path);
  if (sm && DATA.skins.includes(sm[1].toLowerCase())) {{ prefix = "/skin/" + sm[1].toLowerCase(); path = sm[2]; }}
  const isPage = /\\.html?$/i.test(path) || path.endsWith("/");
  if (!isPage) return null;                         // pictures, scripts, indexes: as they are
  let p = path.toLowerCase().replace(/\\/{{2,}}/g, "/");
  if (p.endsWith("/")) p += "index.htm";
  const name = p.slice(p.lastIndexOf("/") + 1);
  if (!search || search === "?") {{
    const want = prefix + (path.endsWith("/") ? path.toLowerCase() : p);
    return want !== pathname ? moved(want) : null;
  }}
  if (p === DATA.searchPage || (p === "/index.htm" && /^\\??skin=o$/.test(search))) return null;
  const params = new Map();
  for (const [n, v] of new URLSearchParams(search)) if (v !== "" && !params.has(n.toLowerCase())) params.set(n.toLowerCase(), v);
  if (name === "golink.htm" && depth === 0) {{
    const u = params.get("url");
    if (!u) return NOT_FOUND;
    let t;
    try {{ t = new URL(u, "http://www.ojuice.net/"); }} catch (e) {{ return NOT_FOUND; }}
    if (!HOSTS.has(t.hostname.toLowerCase())) return NOT_FOUND;
    if (foreign(t.pathname)) return NOT_FOUND;
    return resolve(t.pathname, t.search, depth + 1) || moved(prefix + t.pathname);
  }}
  if (REMOVED.has(name)) return moved(prefix + DATA.archived);
  for (const [k, kind] of DATA.searchKeys) {{
    if (params.has(k)) {{
      if (!kind) return moved(prefix + DATA.archived);
      return moved(prefix + DATA.searchPage + "?t=" + kind + "&q=" + encodeURIComponent(params.get(k)));
    }}
  }}
  const parts = [];
  for (const [k, short] of DATA.queryKeys) {{
    const v = params.get(k);
    if (v !== undefined && /^-?[0-9]{{1,9}}$/.test(v.trim())) parts.push(short + v.trim());
  }}
  const pages = [...params.keys()].filter((k) => k.endsWith("pg")).sort();
  for (const k of pages) {{
    const v = params.get(k).trim();
    if (/^[0-9]{{1,6}}$/.test(v) && Number(v) > 1) parts.push("p" + Number(v));
  }}
  const dot = p.lastIndexOf(".");
  const target = parts.length ? p.slice(0, dot) + "-" + parts.join("-") + p.slice(dot) : p;
  return moved(prefix + target);
}}
// END resolve

BunnySDK.net.http.servePullZone().onOriginRequest((ctx) => {{
  const url = new URL(ctx.request.url);
  const r = resolve(url.pathname, url.search);
  if (!r) return Promise.resolve(ctx.request);
  if (r.status === 301) {{
    return Promise.resolve(new Response(null, {{
      status: 301,
      headers: {{ Location: r.location, "Cache-Control": "public, max-age=86400" }},
    }}));
  }}
  // A path that never exists in the storage zone: the origin answers with its custom 404 page.
  url.pathname = "/.legacy-url-not-in-archive";
  url.search = "";
  return Promise.resolve(new Request(url.toString(), ctx.request));
}});
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if infra/edge/redirects.js is not up to date")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="ascii") != text:
            print(f"{OUT.relative_to(REPO)} is stale: run python3 -I scripts/gen_edge_script.py")
            return 1
        print(f"{OUT.relative_to(REPO)} is up to date.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="ascii")
    print(f"{OUT.relative_to(REPO)}: {len(text) // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
